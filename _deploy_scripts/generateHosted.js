const fs = require('fs');
const path = require('path');
const { wrapHostedFunction } = require('../hosting.utils');

const generateHostedJs = ({
  workspace,
  entryPoints,
  handlerByRouteName,
}) => {
  const exportLines = [];

  for (const entryPoint of entryPoints) {
    const handler = handlerByRouteName.get(entryPoint);
    if (!handler) {
      throw new Error(`No handler found for entry_point: ${ entryPoint }`);
    }

    const relativePath = `./${ handler.filePath.slice(workspace.length + 1) }`;
    exportLines.push(
      `  ${ entryPoint }: wrapHostedFunction(() => require('${ relativePath }'), '${ entryPoint }'),`,
    );
  }

  return `// Generated by mineral — do not edit
const { wrapHostedFunction } = require('@foxtware/mineral/hosting.utils');

module.exports = {
${ exportLines.join('\n') }
};
`;
};

const writeHostedJs = ({
  workspace,
  entryPoints,
  handlerByRouteName,
}) => {
  const hostedPath = path.join(workspace, 'hosted.js');
  const content = generateHostedJs({
    workspace,
    entryPoints,
    handlerByRouteName,
  });

  fs.writeFileSync(hostedPath, content);
  return hostedPath;
};

module.exports = {
  generateHostedJs,
  writeHostedJs,
};
